#include "lib/types/types_interface.h"
#include "lib/types/test.h"
#include "x86-nxvm/chips/hdc/hdc_interface.h"

static lib_bool fail_allocation;
static lib_u32 attempts, live_allocations, signals;

static void *allocate(lib_size count, lib_size size)
{
    ++attempts;
    if (fail_allocation) return LIB_NULL;
    void *memory = lib_allocate_zero(count, size);
    if (memory != LIB_NULL) ++live_allocations;
    return memory;
}

static void release(void *memory)
{
    if (memory != LIB_NULL) {
        lib_test_assert(live_allocations != 0u);
        --live_allocations;
    }
    lib_release(memory);
}

static void signal_level(void *context, lib_bool asserted)
{
    (void)context;
    (void)asserted;
    ++signals;
}

/* Owner-local fault injection; no allocator API is added to the chip. */
#define lib_allocate_zero allocate
#define lib_release release
#include "x86-nxvm/chips/hdc/hdc.c"
#undef lib_allocate_zero
#undef lib_release

static void check_ecc_model(lib_u32 polynomial, lib_u8 limit,
    const lib_u32 expected[5])
{
    x86_hdc_record record = {0}, original, damaged;
    lib_u8 burst;
    for (lib_u32 vector = 0u; vector < 5u; ++vector) {
        lib_memory_set(&record, 0, sizeof(record));
        for (lib_u32 byte = 0u; byte < 512u; ++byte)
            record.data[byte] = vector == 1u ? 0xffu :
                vector == 2u ? (lib_u8)byte :
                vector == 3u && byte == 0u ? 0x80u :
                vector == 4u && byte == 511u ? 1u : 0u;
        x86_hdc_ecc_encode(&record, polynomial);
        for (lib_u32 byte = 0u; byte < 4u; ++byte)
            lib_test_assert(record.ecc[byte] == (lib_u8)(expected[vector] >>
                (24u - 8u * byte)));
        lib_test_assert(record.ecc_present &&
            x86_hdc_ecc_remainder(&record, polynomial, LIB_TRUE) == 0u);
    }
    original = record;
    for (lib_u32 position = 0u; position < 4128u; ++position) {
        const lib_u32 byte = 515u - position / 8u;
        record = original;
        if (byte < 512u) record.data[byte] ^= (lib_u8)(1u << (position & 7u));
        else record.ecc[byte - 512u] ^= (lib_u8)(1u << (position & 7u));
        damaged = record;
        lib_test_assert(!x86_hdc_ecc_check(&record, polynomial, 0u, &burst) &&
            burst == 0u && lib_memory_compare(&record, &damaged, sizeof(record)) == 0);
        lib_test_assert(x86_hdc_ecc_check(&record, polynomial, limit, &burst) &&
            burst == 1u && lib_memory_compare(&record, &original, sizeof(record)) == 0);
    }
    const lib_u32 positions[] = {0u, 31u, 32u, 4096u, 4128u - limit};
    for (lib_size index = 0u; index < sizeof(positions) / sizeof(positions[0]); ++index) {
        record = original;
        for (lib_u32 bit = 0u; bit < limit; ++bit) {
            const lib_u32 position = positions[index] + bit;
            const lib_u32 byte = 515u - position / 8u;
            if (byte < 512u) record.data[byte] ^= (lib_u8)(1u << (position & 7u));
            else record.ecc[byte - 512u] ^= (lib_u8)(1u << (position & 7u));
        }
        lib_test_assert(x86_hdc_ecc_check(&record, polynomial, limit, &burst) &&
            burst == limit && lib_memory_compare(&record, &original, sizeof(record)) == 0);
    }
    record = original;
    for (lib_u32 bit = 0u; bit <= limit; ++bit)
        record.ecc[3u - bit / 8u] ^= (lib_u8)(1u << (bit & 7u));
    damaged = record;
    lib_test_assert(!x86_hdc_ecc_check(&record, polynomial, limit, &burst) &&
        lib_memory_compare(&record, &damaged, sizeof(record)) == 0);
}

lib_i32 main(void)
{
    /* Independent review vectors, not values generated by this implementation. */
    check_ecc_model(0x00a00805u, 11u,
        (const lib_u32[5]){0u, 0x64fff4d8u, 0x3b404e21u, 0xd6800eb4u, 0x00a00805u});
    check_ecc_model(0x140a0445u, 5u,
        (const lib_u32[5]){0u, 0x0830d99du, 0x3fd4534cu, 0x062db771u, 0x140a0445u});
    const x86_hdc_connection connection = {.irq = signal_level, .drq = signal_level};
    for (lib_u32 protocol = X86_HDC_PROTOCOL_ATA_PIO;
        protocol <= X86_HDC_PROTOCOL_XEBEC_XT; ++protocol) {
        x86_hdc_config config = {.protocol = (x86_hdc_protocol)protocol};
        x86_hdc *hdc = (x86_hdc *)&config;
        fail_allocation = LIB_TRUE;
        attempts = signals = 0u;
        lib_test_assert(x86_hdc_create(&config, &connection, &hdc) == LIB_STATUS_NO_MEMORY);
        lib_test_assert(hdc == LIB_NULL && attempts == 1u && signals == 0u &&
            live_allocations == 0u);
        fail_allocation = LIB_FALSE;
        lib_test_assert(x86_hdc_create(&config, &connection, &hdc) == LIB_STATUS_OK);
        lib_test_assert(hdc != LIB_NULL && live_allocations == 1u);
        x86_hdc_destroy(hdc);
        lib_test_assert(live_allocations == 0u);
    }
    x86_hdc_config invalid = {.protocol = (x86_hdc_protocol)99};
    x86_hdc *hdc = (x86_hdc *)&invalid;
    attempts = signals = 0u;
    lib_test_assert(x86_hdc_create(&invalid, &connection, &hdc) == LIB_STATUS_INVALID_ARGUMENT);
    lib_test_assert(hdc == LIB_NULL && attempts == 0u && signals == 0u);
    x86_hdc_destroy(LIB_NULL);
    return 0;
}
