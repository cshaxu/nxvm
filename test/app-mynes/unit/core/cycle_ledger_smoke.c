    case 0x88u: case 0xbau: case 0xc6u: case 0xcau: case 0xceu: case 0xd6u: case 0xdeu:
    case 0xe1u: case 0xe5u: case 0xe9u: case 0xedu: case 0xf1u: case 0xf5u: case 0xf9u: case 0xfdu:
