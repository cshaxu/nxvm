#include <assert.h>
#include <string.h>

#include "core/machine_interface.h"
#include "core/opcode_interface.h"

static lib_bool is_official(lib_u8 opcode)
{
    static const lib_u8 values[] = { 0x00u,0x01u,0x05u,0x06u,0x08u,0x09u,0x0au,0x0du,0x0eu,0x10u,0x11u,0x15u,0x16u,0x18u,0x19u,0x1du,0x1eu,0x20u,0x21u,0x24u,0x25u,0x26u,0x28u,0x29u,0x2au,0x2cu,0x2du,0x2eu,0x30u,0x31u,0x35u,0x36u,0x38u,0x39u,0x3du,0x3eu,0x40u,0x41u,0x45u,0x46u,0x48u,0x49u,0x4au,0x4cu,0x4du,0x4eu,0x50u,0x51u,0x55u,0x56u,0x58u,0x59u,0x5du,0x5eu,0x60u,0x61u,0x65u,0x66u,0x68u,0x69u,0x6au,0x6cu,0x6du,0x6eu,0x70u,0x71u,0x75u,0x76u,0x78u,0x79u,0x7du,0x7eu,0x81u,0x84u,0x85u,0x86u,0x88u,0x8au,0x8cu,0x8du,0x8eu,0x90u,0x91u,0x94u,0x95u,0x96u,0x98u,0x99u,0x9au,0x9du,0xa0u,0xa1u,0xa2u,0xa4u,0xa5u,0xa6u,0xa8u,0xa9u,0xaau,0xacu,0xadu,0xaeu,0xb0u,0xb1u,0xb4u,0xb5u,0xb6u,0xb8u,0xb9u,0xbau,0xbcu,0xbdu,0xbeu,0xc0u,0xc1u,0xc4u,0xc5u,0xc6u,0xc8u,0xc9u,0xcau,0xccu,0xcdu,0xceu,0xd0u,0xd1u,0xd5u,0xd6u,0xd8u,0xd9u,0xddu,0xdeu,0xe0u,0xe1u,0xe4u,0xe5u,0xe6u,0xe8u,0xe9u,0xeau,0xecu,0xedu,0xeeu,0xf0u,0xf1u,0xf5u,0xf6u,0xf8u,0xf9u,0xfdu,0xfeu };
    lib_size index;
    for (index = 0u; index < sizeof(values); ++index)
        if (values[index] == opcode) return LIB_TRUE;
    return LIB_FALSE;
}

int main(void)
{
    lib_u8 bytes[16u + 16384u];
    core_machine_options options = { 0 };
    lib_u32 opcode;
    for (opcode = 0u; opcode < 256u; ++opcode) {
        core_machine *machine = 0;
        core_run_result result;
        core_opcode_metadata metadata;
        memset(bytes, 0, sizeof(bytes));
        bytes[0] = 'N'; bytes[1] = 'E'; bytes[2] = 'S'; bytes[3] = 0x1au;
        bytes[4] = 1u; bytes[16u] = (lib_u8)opcode;
        bytes[16u + 0x3ffcu] = 0u; bytes[16u + 0x3ffdu] = 0x80u;
        bytes[16u + 0x3ffeu] = 0u; bytes[16u + 0x3fffu] = 0x80u;
        assert(core_machine_create(&machine, bytes, sizeof(bytes), &options) == LIB_STATUS_OK);
        assert(core_opcode_describe((lib_u8)opcode, &metadata) ==
            is_official((lib_u8)opcode));
        if (is_official((lib_u8)opcode)) {
            assert(metadata.mnemonic[0] != '\0');
            assert(metadata.bytes >= 1u && metadata.bytes <= 3u);
        }
        assert(core_machine_run(machine, 1u, 20u, &result) == LIB_STATUS_OK);
        assert(result.trap_valid == !is_official((lib_u8)opcode));
        if (is_official((lib_u8)opcode)) {
            assert(result.instructions == 1u);
        } else {
            core_observation observation;
            assert(result.instructions == 0u && result.cycles == 1u);
            assert(core_machine_observe(machine, &observation) == LIB_STATUS_OK);
            assert(observation.trap_reason == CORE_MACHINE_STOP_UNSUPPORTED_OPCODE);
            assert(observation.trap_pc == 0x8000u && observation.trap_opcode == (lib_u8)opcode);
        }
        core_machine_destroy(machine);
    }
    return 0;
}
