#include <assert.h>
#include "app-myraidenii/machine/image_hash.h"

int main(void)
{
    static const lib_u8 empty[MYRAIDENII_MACHINE_IMAGE_SHA256_BYTES] = {
        0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,
        0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55};
    static const lib_u8 abc[MYRAIDENII_MACHINE_IMAGE_SHA256_BYTES] = {
        0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,
        0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad};
    lib_u8 digest[MYRAIDENII_MACHINE_IMAGE_SHA256_BYTES];
    myraidenii_machine_image_sha256(LIB_NULL,0u,digest);
    assert(lib_memory_compare(digest,empty,sizeof(digest))==0);
    myraidenii_machine_image_sha256((const lib_u8 *)"abc",3u,digest);
    assert(lib_memory_compare(digest,abc,sizeof(digest))==0);
    return 0;
}
